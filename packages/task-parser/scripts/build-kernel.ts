/**
 * Builds the WebAssembly SIMD matrix kernel used by src/model/network.ts.
 * The text format is generated here (16 accumulators are tedious by hand),
 * compiled with wabt, and written as base64 to src/model/kernel-wasm.ts.
 * Usage: bun scripts/build-kernel.ts
 */
import { writeFile } from "node:fs/promises";

const BLOCK = [0, 1, 2, 3];
const pairs = BLOCK.flatMap((i) => BLOCK.map((j) => [i, j] as const));
const locals = [
  ...BLOCK.map((i) => `(local $x${i} i32)`),
  ...BLOCK.map((j) => `(local $w${j} i32)`),
  ...pairs.map(([i, j]) => `(local $a${i}${j} v128)`),
  ...BLOCK.map((i) => `(local $xv${i} v128)`),
  ...BLOCK.map((j) => `(local $wv${j} v128)`),
].join(" ");
const lane = (name: string, index: number) =>
  `(f32x4.extract_lane ${index} (local.get ${name}))`;
const hsum = (name: string) =>
  `(f32.add (f32.add ${lane(name, 0)} ${lane(name, 1)}) (f32.add ${lane(name, 2)} ${lane(name, 3)}))`;

/**
 * out[n, rows] = x[n, cols] · w[rows, cols]ᵀ, all float32, byte offsets.
 * n, rows and cols must be multiples of 4 (callers pad).
 */
/** `a += x · w`, fused where relaxed SIMD allows (one rounding less, 2× faster). */
const madd = (fused: boolean) => (i: number, j: number) =>
  fused
    ? `(local.set $a${i}${j} (f32x4.relaxed_madd (local.get $xv${i}) (local.get $wv${j}) (local.get $a${i}${j})))`
    : `(local.set $a${i}${j} (f32x4.add (local.get $a${i}${j}) (f32x4.mul (local.get $xv${i}) (local.get $wv${j}))))`;

const kernel = (fused: boolean) => {
  const MADD = madd(fused);
  return `(module
  (memory (export "memory") 1)
  (func (export "linear")
    (param $x i32) (param $n i32) (param $w i32) (param $rows i32)
    (param $cols i32) (param $out i32)
    (local $t i32) (local $r i32) (local $c i32) (local $stride i32)
    (local $ostride i32) (local $o i32)
    ${locals}
    (local.set $stride (i32.shl (local.get $cols) (i32.const 2)))
    (local.set $ostride (i32.shl (local.get $rows) (i32.const 2)))
    ;; Rows outside, tokens inside: a 4-row weight block stays in L1 while
    ;; every token passes over it, so each weight is read from memory once.
    (block $rdone (loop $rloop
      (br_if $rdone (i32.ge_u (local.get $r) (local.get $rows)))
      (local.set $w0 (i32.add (local.get $w) (i32.mul (local.get $r) (local.get $stride))))
      ${BLOCK.slice(1)
        .map(
          (j) =>
            `(local.set $w${j} (i32.add (local.get $w${j - 1}) (local.get $stride)))`
        )
        .join("\n      ")}
      (local.set $t (i32.const 0))
      (block $tdone (loop $tloop
        (br_if $tdone (i32.ge_u (local.get $t) (local.get $n)))
        (local.set $x0 (i32.add (local.get $x) (i32.mul (local.get $t) (local.get $stride))))
        ${BLOCK.slice(1)
          .map(
            (i) =>
              `(local.set $x${i} (i32.add (local.get $x${i - 1}) (local.get $stride)))`
          )
          .join("\n        ")}
        ${pairs.map(([i, j]) => `(local.set $a${i}${j} (v128.const f32x4 0 0 0 0))`).join("\n        ")}
        (local.set $c (i32.const 0))
        (block $cdone (loop $cloop
          (br_if $cdone (i32.ge_u (local.get $c) (local.get $stride)))
          ${BLOCK.map((i) => `(local.set $xv${i} (v128.load (i32.add (local.get $x${i}) (local.get $c))))`).join("\n          ")}
          ${BLOCK.map((j) => `(local.set $wv${j} (v128.load (i32.add (local.get $w${j}) (local.get $c))))`).join("\n          ")}
          ${pairs.map(([i, j]) => MADD(i, j)).join("\n          ")}
          (local.set $c (i32.add (local.get $c) (i32.const 16)))
          (br $cloop)))
        (local.set $o (i32.add (local.get $out) (i32.add (i32.mul (local.get $t) (local.get $ostride)) (i32.shl (local.get $r) (i32.const 2)))))
        ${BLOCK.map(
          (i) =>
            `${BLOCK.map((j) => `(f32.store offset=${j * 4} (local.get $o) ${hsum(`$a${i}${j}`)})`).join("\n        ")}
        (local.set $o (i32.add (local.get $o) (local.get $ostride)))`
        ).join("\n        ")}
        (local.set $t (i32.add (local.get $t) (i32.const 4)))
        (br $tloop)))
      (local.set $r (i32.add (local.get $r) (i32.const 4)))
      (br $rloop)))))
`;
};

const wabt = await (await import("wabt")).default();
function compile(fused: boolean) {
  const module = wabt.parseWat("kernel.wat", kernel(fused), {
    relaxed_simd: fused,
    simd: true,
  });
  module.validate();
  return Buffer.from(module.toBinary({}).buffer).toString("base64");
}
const plainKernel = compile(false);
const fusedKernel = compile(true);
await writeFile(
  new URL("../src/model/kernel-wasm.ts", import.meta.url),
  `/** Generated by scripts/build-kernel.ts; do not edit. */
export const KERNEL_WASM =
  "${plainKernel}";
/** The same kernel with fused multiply-add (relaxed SIMD). */
export const KERNEL_FMA_WASM =
  "${fusedKernel}";
`
);
console.log(
  `kernels: ${plainKernel.length} / ${fusedKernel.length} base64 chars`
);
