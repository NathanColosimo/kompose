import {
  date,
  index,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { createSelectSchema } from "drizzle-orm/zod";
import z from "zod";
import { connectionTable } from "./connection";

export const activityKinds = ["sleep", "workout"] as const;

export type ActivityKind = (typeof activityKinds)[number];

/** What each kind of activity carries besides its times. */
export const activityDetailsSchemas = {
  sleep: z.object({
    /** Time asleep, which is less than the time in bed. */
    asleepMinutes: z.number().int().nonnegative().nullable(),
    nap: z.boolean(),
  }),
  workout: z.object({
    /** WHOOP's 0 to 21 scale. */
    strain: z.number().nullable(),
  }),
} satisfies Record<ActivityKind, z.ZodType>;

export type ActivityDetails = {
  [Kind in ActivityKind]: z.infer<(typeof activityDetailsSchemas)[Kind]>;
};

/**
 * Something a plugin recorded that happened over a stretch of time and can't
 * be edited in Kompose: a sleep, a workout. See documents/plugins.md.
 */
export const activityTable = pgTable(
  "activity",
  {
    connectionId: uuid("connection_id")
      .notNull()
      .references(() => connectionTable.id, { onDelete: "cascade" }),
    /**
     * The day the provider counts it toward, which the times alone don't
     * give: a sleep counts toward the day the user woke up.
     */
    date: date("date", { mode: "string" }).notNull(),
    details: jsonb("details").$type<ActivityDetails[ActivityKind]>().notNull(),
    endAt: timestamp("end_at", { mode: "date", withTimezone: true }).notNull(),
    /** The provider's ID for it. */
    externalId: text("external_id").notNull(),
    id: uuid("id").primaryKey(), // UUIDv7 generated by application
    /** Text, not a Postgres enum, so a new kind needs no migration. */
    kind: text("kind", { enum: activityKinds }).notNull(),
    startAt: timestamp("start_at", {
      mode: "date",
      withTimezone: true,
    }).notNull(),
    /** The provider's name for it, such as a workout's sport. */
    title: text("title"),
  },
  (table) => [
    uniqueIndex("activity_connection_external_id_unique").on(
      table.connectionId,
      table.externalId
    ),
    index("activity_connection_date_idx").on(table.connectionId, table.date),
  ]
);

const activityRowSchema = createSelectSchema(activityTable);

/** A row with its `details` checked against its `kind`. */
export const activitySelectSchema = z.discriminatedUnion("kind", [
  activityRowSchema.safeExtend({
    details: activityDetailsSchemas.sleep,
    kind: z.literal("sleep"),
  }),
  activityRowSchema.safeExtend({
    details: activityDetailsSchemas.workout,
    kind: z.literal("workout"),
  }),
]);

export type Activity = z.infer<typeof activitySelectSchema>;
